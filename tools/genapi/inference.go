// routeTable renders one handwritten REST route slice.
func routeTable(name, comment string, rows []route) []byte {
	var body strings.Builder
	fmt.Fprint(&body, "// Code generated by tools/genapi; DO NOT EDIT.\npackage generated\n\n")
	fmt.Fprintf(&body, "// %s %s\n", name, comment)
	fmt.Fprintf(&body, "var %s = []Route{\n", name)
	for _, entry := range rows {
		fmt.Fprintf(&body, "\t{%q, %q, %q, %t, %t},\n", entry.ID, entry.Verb, entry.Path, entry.JSON, entry.Media)
	}
	fmt.Fprint(&body, "}\n")
	return []byte(body.String())
}

// vertexAIRoutes generates the Vertex AI publisher-model inference slice for
// the v1 and v1beta1 surfaces; google-genai selects v1beta1 for Vertex AI. The
// IDs are the aiplatform discovery method IDs.
func vertexAIRoutes() []byte {
	const prefix = "aiplatform.projects.locations.publishers.models."
	versions := []string{"v1", "v1beta1"}
	methods := []string{"generateContent", "streamGenerateContent", "countTokens", "predict", "embedContent"}
	rows := make([]route, 0, len(versions)*len(methods))
	for _, version := range versions {
		model := "/" + version + "/projects/{project}/locations/{location}/publishers/google/models/{model}"
		for _, method := range methods {
			rows = append(rows, route{prefix + method, http.MethodPost, model + ":" + method, true, false})
		}
	}
	return routeTable("VertexAIRoutes", "is the Vertex AI publisher-model inference route table.", rows)
}

// loggingRoutes generates the Cloud Logging v2 REST slice. The log ID is one
// URL-encoded path segment, as the API requires.
func loggingRoutes() []byte {
	rows := []route{
		{"logging.entries.write", http.MethodPost, "/v2/entries:write", true, false},
		{"logging.entries.list", http.MethodPost, "/v2/entries:list", true, false},
		{"logging.projects.logs.list", http.MethodGet, "/v2/projects/{project}/logs", false, false},
		{"logging.projects.logs.delete", http.MethodDelete, "/v2/projects/{project}/logs/{log}", false, false},
	}
	return routeTable("LoggingRoutes", "is the Cloud Logging v2 REST route table slice.", rows)
}

// loggingDispatch generates the LoggingServiceV2 gRPC forwarding stubs from the
// pinned module's descriptors. A method whose HTTP binding carries no resource
// variable (entries write/list, descriptor listing, tail) gets an empty
// selector: the provider resolves and authorizes every project it names.
func loggingDispatch() []byte {
	out := header(`// Code generated by tools/genapi; DO NOT EDIT.
package generated
import (
 "context"
 "cloud.google.com/go/logging/apiv2/loggingpb"
 "google.golang.org/grpc/codes"
 "google.golang.org/grpc/status"
 "google.golang.org/protobuf/proto"
 "google.golang.org/protobuf/types/known/emptypb"
)
`)
	var descriptors bytes.Buffer
	descriptors.WriteString("var LoggingMethods = []RPC{\n")
	service := loggingpb.File_google_logging_v2_logging_proto.Services().ByName("LoggingServiceV2")
	name := string(service.Name())
	fmt.Fprintf(&out, "type %sServer struct { loggingpb.Unimplemented%sServer; Dispatch PubSubDispatch }\n", name, name)
	for j := range service.Methods().Len() {
		m := service.Methods().Get(j)
		methodName := string(m.Name())
		id := "/" + string(service.FullName()) + "/" + methodName
		input, output := goType(m.Input()), goType(m.Output())
		streaming := m.IsStreamingClient() || m.IsStreamingServer()
		field, pattern := "", ""
		if rule, ok := proto.GetExtension(m.Options(), annotations.E_Http).(*annotations.HttpRule); ok && rule != nil {
			if match := resourceVariable.FindStringSubmatch(rulePath(rule)); match != nil {
				field, pattern = match[1], match[2]
			}
		}
		if streaming {
			if !m.IsStreamingClient() || !m.IsStreamingServer() {
				panic("Unsupported new Logging streaming shape; update generator")
			}
			fmt.Fprintf(&out, "func(s *%sServer) %s(stream loggingpb.%s_%sServer) error { return s.Dispatch.Stream(%q,stream) }\n", name, methodName, name, methodName, id)
		} else {
			unaryStub(&out, name, methodName, input, output, id)
		}
		rpcDescriptor(&descriptors, id, field, pattern, streaming, input, output)
	}
	descriptors.WriteString("}\n")
	out.Write(descriptors.Bytes())
	return out.Bytes()
}
