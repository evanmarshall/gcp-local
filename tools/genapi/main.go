// Command genapi reproduces transport contracts, without provider semantics.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"cloud.google.com/go/iam/apiv1/iampb"
	pb "cloud.google.com/go/pubsub/v2/apiv1/pubsubpb"
	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
)

type method struct {
	ID       string         `json:"id"`
	Verb     string         `json:"httpMethod"`
	Path     string         `json:"path"`
	Request  map[string]any `json:"request"`
	Download bool           `json:"supportsMediaDownload"`
	Media    *struct {
		Protocols map[string]struct {
			Path string `json:"path"`
		} `json:"protocols"`
	} `json:"mediaUpload"`
}
type resource struct {
	Methods   map[string]method   `json:"methods"`
	Resources map[string]resource `json:"resources"`
}
type route struct {
	ID, Verb, Path string
	JSON, Media    bool
}

func main() {
	check := flag.Bool("check", false, "fail if generated output differs")
	flag.Parse()
	raw, err := os.ReadFile("api/discovery/storage-v1.json")
	must(err)
	var manifest struct {
		SHA string `json:"sha256"`
	}
	read("api/discovery/manifest.json", &manifest)
	sum := sha256.Sum256(raw)
	if hex.EncodeToString(sum[:]) != manifest.SHA {
		panic("Storage discovery checksum mismatch")
	}
	var discovery resource
	must(json.Unmarshal(raw, &discovery))
	var routes []route
	var walk func(resource)
	walk = func(r resource) {
		for _, m := range r.Methods {
			routes = append(routes, route{m.ID, m.Verb, "/storage/v1/" + m.Path, len(m.Request) > 0, false})
			if m.Download {
				routes = append(routes, route{m.ID, m.Verb, "/download/storage/v1/" + m.Path, false, false})
			}
			if m.Media != nil {
				for _, p := range m.Media.Protocols {
					routes = append(routes, route{m.ID, m.Verb, p.Path, false, true})
				}
			}
		}
		for _, child := range r.Resources {
			walk(child)
		}
	}
	walk(discovery)
	sort.Slice(routes, func(i, j int) bool { a, b := routes[i], routes[j]; return a.Path+a.Verb < b.Path+b.Verb })
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/genapi; DO NOT EDIT.\npackage generated\n\ntype Route struct { Method, Verb, Path string; JSONBody, Media bool }\nvar StorageRoutes = []Route{\n")
	for _, r := range routes {
		fmt.Fprintf(&out, "{%q,%q,%q,%v,%v},\n", r.ID, r.Verb, r.Path, r.JSON, r.Media)
	}
	out.WriteString("}\n")
	write("storage_routes.go", out.Bytes(), *check)

	// The pinned Google module supplies protoc-generated wire types/descriptors.
	// Generate our forwarding stubs and resource selectors from those descriptors.
	out.Reset()
	out.WriteString(`// Code generated by tools/genapi; DO NOT EDIT.
package generated
import (
 "context"
 pb "cloud.google.com/go/pubsub/v2/apiv1/pubsubpb"
 "google.golang.org/grpc"
 "google.golang.org/grpc/codes"
 "google.golang.org/grpc/status"
 "google.golang.org/protobuf/proto"
 "google.golang.org/protobuf/types/known/emptypb"
)
type PubSubDispatch interface {
 Unary(context.Context, string, proto.Message) (proto.Message,error)
 Stream(string, grpc.ServerStream) error
}
type RPC struct { Method, ResourceField, ResourcePattern string; Streaming bool; NewRequest, NewResponse func() proto.Message }
`)
	var descriptors bytes.Buffer
	descriptors.WriteString("var PubSubMethods = []RPC{\n")
	services := pb.File_google_pubsub_v1_pubsub_proto.Services()
	var resourceVariable = regexp.MustCompile(`\{([^=}]+)=([^}]+)\}`)
	for i := range services.Len() {
		service := services.Get(i)
		name := string(service.Name())
		fmt.Fprintf(&out, "type %sServer struct { pb.Unimplemented%sServer; Dispatch PubSubDispatch }\n", name, name)
		for j := range service.Methods().Len() {
			m := service.Methods().Get(j)
			methodName := string(m.Name())
			id := "/" + string(service.FullName()) + "/" + methodName
			input, output := goType(m.Input()), goType(m.Output())
			field, pattern := "", ""
			if proto.HasExtension(m.Options(), annotations.E_Http) {
				rule, ok := proto.GetExtension(m.Options(), annotations.E_Http).(*annotations.HttpRule)
				if !ok {
					panic("method " + methodName + " has a non-HTTP annotation")
				}
				path := rule.GetGet() + rule.GetPost() + rule.GetPut() + rule.GetPatch() + rule.GetDelete()
				if match := resourceVariable.FindStringSubmatch(path); match != nil {
					field, pattern = match[1], match[2]
				}
			}
			streaming := m.IsStreamingClient() || m.IsStreamingServer()
			if streaming {
				if methodName != "StreamingPull" || !m.IsStreamingClient() || !m.IsStreamingServer() {
					panic("Unsupported new streaming shape; update generator")
				}
				field, pattern = "subscription", "projects/*/subscriptions/*"
				fmt.Fprintf(&out, "func(s *%sServer) %s(stream pb.%s_%sServer) error { return s.Dispatch.Stream(%q,stream) }\n", name, methodName, name, methodName, id)
			} else {
				fmt.Fprintf(&out, `func(s *%sServer) %s(ctx context.Context, request *%s) (*%s,error) {
 result,err:=s.Dispatch.Unary(ctx,%q,request); if err!=nil{return nil,err}
 response,ok:=result.(*%s); if !ok || response==nil{return nil,status.Error(codes.Internal,"Provider returned an invalid response type")}; return response,nil
}
`, name, methodName, input, output, id, output)
			}
			if field == "" {
				panic("Missing resource selector for " + id)
			}
			fmt.Fprintf(&descriptors, "{%q,%q,%q,%v,func() proto.Message{return &%s{}},func() proto.Message{return &%s{}}},\n", id, field, pattern, streaming, input, output)
		}
	}
	descriptors.WriteString("}\n")
	out.Write(descriptors.Bytes())
	write("pubsub_dispatch.go", out.Bytes(), *check)
	// IAMPolicy is shared on the wire. Only the Pub/Sub provider registers its
	// supported resource kinds today; generated bindings grant no coverage.
	out.Reset()
	out.WriteString(`// Code generated by tools/genapi; DO NOT EDIT.
package generated
import (
 "context"
 "cloud.google.com/go/iam/apiv1/iampb"
 "google.golang.org/grpc/codes"
 "google.golang.org/grpc/status"
 "google.golang.org/protobuf/proto"
)
type IAMPolicyServer struct { iampb.UnimplementedIAMPolicyServer; Dispatch PubSubDispatch }
`)
	descriptors.Reset()
	descriptors.WriteString("var IAMMethods = []RPC{\n")
	iamService := iampb.File_google_iam_v1_iam_policy_proto.Services().ByName("IAMPolicy")
	for i := range iamService.Methods().Len() {
		m := iamService.Methods().Get(i)
		if m.IsStreamingClient() || m.IsStreamingServer() {
			panic("Unexpected IAM stream")
		}
		id := "/" + string(iamService.FullName()) + "/" + string(m.Name())
		input, output := goType(m.Input()), goType(m.Output())
		fmt.Fprintf(&out, `func(s *IAMPolicyServer) %s(ctx context.Context, request *%s) (*%s,error) {
 result,err:=s.Dispatch.Unary(ctx,%q,request); if err!=nil{return nil,err}
 response,ok:=result.(*%s); if !ok || response==nil{return nil,status.Error(codes.Internal,"Provider returned an invalid response type")}; return response,nil
}
`, m.Name(), input, output, id, output)
		fmt.Fprintf(&descriptors, "{%q,\"resource\",\"**\",false,func() proto.Message{return &%s{}},func() proto.Message{return &%s{}}},\n", id, input, output)
	}
	descriptors.WriteString("}\n")
	out.Write(descriptors.Bytes())
	write("iam_dispatch.go", out.Bytes(), *check)
}
func goType(d protoreflect.MessageDescriptor) string {
	if d.FullName() == "google.protobuf.Empty" {
		return "emptypb.Empty"
	}
	if strings.HasPrefix(string(d.FullName()), "google.pubsub.v1.") {
		return "pb." + string(d.Name())
	}
	if strings.HasPrefix(string(d.FullName()), "google.iam.v1.") {
		return "iampb." + string(d.Name())
	}
	panic("Unknown external message type: " + string(d.FullName()))
}
func read(path string, dst any) {
	raw, err := os.ReadFile(path) //nolint:gosec // generator input from this repository
	must(err)
	must(json.Unmarshal(raw, dst))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func write(name string, raw []byte, check bool) {
	formatted, err := format.Source(raw)
	must(err)
	path := filepath.Join("api/generated", name)
	if check {
		current, err := os.ReadFile(path) //nolint:gosec // generated output inside this repository
		must(err)
		if !bytes.Equal(current, formatted) {
			panic("Generated output differs: " + path)
		}
		return
	}
	must(os.WriteFile(path, formatted, 0644)) //nolint:gosec // a committed source file needs group/other read
}
