// firestoreSelector merges a method's HTTP bindings into one resource field
// and pattern. Firestore binds the database root and nested documents
// separately ({A} and {A/*/**}); the merged pattern A/** accepts both. A
// trailing ** matches zero or more segments.
func firestoreSelector(m protoreflect.MethodDescriptor) (string, string) {
	rule, ok := proto.GetExtension(m.Options(), annotations.E_Http).(*annotations.HttpRule)
	if !ok || rule == nil {
		panic("Missing HTTP binding for Firestore " + string(m.Name()))
	}
	bindings := append([]*annotations.HttpRule{rule}, rule.GetAdditionalBindings()...)
	field := ""
	patterns := make([]string, 0, len(bindings))
	for _, binding := range bindings {
		path := rulePath(binding)
		match := resourceVariable.FindStringSubmatch(path)
		if match == nil || (field != "" && match[1] != field) {
			panic("Unsupported Firestore resource binding for " + string(m.Name()))
		}
		field = match[1]
		patterns = append(patterns, match[2])
	}
	return field, mergePatterns(string(m.Name()), patterns)
}

// mergePatterns joins a root binding A and its nested binding A/*/** into A/**.
func mergePatterns(method string, patterns []string) string {
	if len(patterns) == 1 {
		return patterns[0]
	}
	if len(patterns) == 2 {
		root, nested := patterns[0], patterns[1]
		if len(root) > len(nested) {
			root, nested = nested, root
		}
		if nested == root+"/*/**" {
			return root + "/**"
		}
	}
	panic("Unsupported Firestore binding shape for " + method)
}

// resourceVariable matches a {field=pattern} path variable in an HTTP rule.
var resourceVariable = regexp.MustCompile(`\{([^=}]+)=([^}]+)\}`)

// rulePath returns the path of an HTTP rule, whichever verb it binds.
func rulePath(rule *annotations.HttpRule) string {
	return rule.GetGet() + rule.GetPost() + rule.GetPut() + rule.GetPatch() + rule.GetDelete()
}

// readDiscovery reads a pinned discovery document and panics unless it
// matches the checksum recorded in its manifest.
func readDiscovery(path, manifestPath, label string) []byte {
	raw, err := os.ReadFile(path) //nolint:gosec // generator input from this repository
	must(err)
	var manifest struct {
		SHA string `json:"sha256"`
	}
	read(manifestPath, &manifest)
	sum := sha256.Sum256(raw)
	if hex.EncodeToString(sum[:]) != manifest.SHA {
		panic(label + " discovery checksum mismatch")
	}
	return raw
}

// unaryStub writes a typed unary forwarding method onto a generated server.
func unaryStub(out *bytes.Buffer, server, method, input, output, id string) {
	fmt.Fprintf(out, `func(s *%sServer) %s(ctx context.Context, request *%s) (*%s,error) {
 result,err:=s.Dispatch.Unary(ctx,%q,request); if err!=nil{return nil,err}
 response,ok:=result.(*%s); if !ok || response==nil{return nil,status.Error(codes.Internal,"Provider returned an invalid response type")}; return response,nil
}
`, server, method, input, output, id, output)
}

// rpcDescriptor writes one RPC row: the method's resource selector, whether
// it streams, and constructors for its request and response messages.
func rpcDescriptor(out *bytes.Buffer, id, field, pattern string, streaming bool, input, output string) {
	fmt.Fprintf(out, "{Method: %q, ResourceField: %q, ResourcePattern: %q, Streaming: %v, NewRequest: func() proto.Message{return &%s{}}, NewResponse: func() proto.Message{return &%s{}}},\n", id, field, pattern, streaming, input, output)
}

// header starts one generated file buffer.
