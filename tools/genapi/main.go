// dataDispatch generates typed forwarding stubs and resource selectors for an
// allowlisted unary/server-streaming slice of one gRPC service.
func dataDispatch(d dataService) []byte {
	name := string(d.service.Name())
	var stubs, descriptors bytes.Buffer
	usesEmpty := false
	fmt.Fprintf(&stubs, "type %sServer struct { %s.Unimplemented%sServer; Dispatch contract.GRPCDispatch }\n", name, d.alias, name)
	fmt.Fprintf(&descriptors, "var %s = []contract.RPC{\n", d.variable)
	typeOf := func(m protoreflect.MessageDescriptor) string {
		if m.FullName() == "google.protobuf.Empty" {
			usesEmpty = true
			return "emptypb.Empty"
		}
		if m.ParentFile().Package() != d.service.ParentFile().Package() {
			panic("Unknown external message type: " + string(m.FullName()))
		}
		return d.alias + "." + string(m.Name())
	}
	for _, methodName := range d.methods {
		m := d.service.Methods().ByName(protoreflect.Name(methodName))
		if m == nil {
			panic("Allowlisted method is missing: " + methodName)
		}
		if m.IsStreamingClient() {
			panic("Unsupported client-streaming method " + methodName + "; update generator")
		}
		id := "/" + string(d.service.FullName()) + "/" + methodName
		input, output := typeOf(m.Input()), typeOf(m.Output())
		field, pattern := httpSelector(m, id)
		streaming := m.IsStreamingServer()
		if streaming {
			fmt.Fprintf(&stubs, "func(s *%sServer) %s(request *%s, stream %s.%s_%sServer) error { return s.Dispatch.ServerStream(%q,request,stream) }\n",
				name, methodName, input, d.alias, name, methodName, id)
		} else {
			unaryStub(&stubs, name, methodName, input, output, id)
		}
		rpcDescriptor(&descriptors, id, field, pattern, streaming, input, output)
	}
	descriptors.WriteString("}\n")
	out := header("// Code generated by tools/genapi; DO NOT EDIT.\npackage generated\nimport (\n \"context\"\n \"github.com/evanmarshall/gcp-local/api/generated/contract\"\n " +
		fmt.Sprintf("%q", d.importPath) + "\n \"google.golang.org/grpc/codes\"\n \"google.golang.org/grpc/status\"\n \"google.golang.org/protobuf/proto\"\n")
	if usesEmpty {
		out.WriteString(" \"google.golang.org/protobuf/types/known/emptypb\"\n")
	}
	out.WriteString(")\n")
	out.Write(stubs.Bytes())
	out.Write(descriptors.Bytes())
	return out.Bytes()
}

// httpSelector reads the first path variable of a method's HTTP annotation.
func httpSelector(m protoreflect.MethodDescriptor, id string) (string, string) {
	rule, ok := proto.GetExtension(m.Options(), annotations.E_Http).(*annotations.HttpRule)
	if !ok || rule == nil {
		panic("Missing HTTP annotation for " + id)
	}
	path := rulePath(rule)
	match := resourceVariable.FindStringSubmatch(path)
	if match == nil {
		panic("Missing resource selector for " + id)
	}
	return match[1], match[2]
}

