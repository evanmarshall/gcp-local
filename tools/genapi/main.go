// cloudSQLRoutes generates the Cloud SQL Admin v1beta4 route slice from the
// pinned discovery document, checksum-verified against its manifest. The
// v1beta4 paths carry a /sql/v1beta4 prefix; the v1 paths would collide with
// the Spanner admin routes on this path-only gateway.
func cloudSQLRoutes() []byte {
	raw := readDiscovery("api/discovery/sqladmin-v1beta4.json", "api/discovery/sqladmin-v1beta4.manifest.json", "Cloud SQL")
	var discovery resource
	must(json.Unmarshal(raw, &discovery))
	methods := map[string]method{}
	for _, child := range discovery.Resources {
		for _, m := range child.Methods {
			methods[m.ID] = m
		}
	}
	rows := make([]route, 0, len(cloudSQLMethods))
	for _, id := range cloudSQLMethods {
		m, ok := methods[id]
		if !ok {
			panic("Cloud SQL discovery lacks " + id)
		}
		rows = append(rows, route{m.ID, m.Verb, "/" + m.Path, len(m.Request) > 0, false})
	}
	return routeTable("CloudSQLRoutes", "is the Cloud SQL Admin v1beta4 route table slice.", rows)
}
