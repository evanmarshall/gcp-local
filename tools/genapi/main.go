// contractTypes generates the row and dispatch types every service package's
// tables and stubs share.
func contractTypes() []byte {
	return []byte(`// Code generated by tools/genapi; DO NOT EDIT.
package generated
import (
 "context"
 "google.golang.org/grpc"
 "google.golang.org/protobuf/proto"
)
type Route struct { Method, Verb, Path string; JSONBody, Media bool }
type PubSubDispatch interface {
 Unary(context.Context, string, proto.Message) (proto.Message,error)
 Stream(string, grpc.ServerStream) error
}
type RPC struct { Method, ResourceField, ResourcePattern string; Streaming bool; NewRequest, NewResponse func() proto.Message }
// GRPCDispatch adds server-streaming dispatch: the client sends one request
// and the provider relays a response stream.
type GRPCDispatch interface {
 PubSubDispatch
 ServerStream(string, proto.Message, grpc.ServerStream) error
}
// Transcoding pairs one gRPC method with the REST route whose provider method
// serves it. Verb, Path, and Body come from the method's primary
// google.api.http binding; Field is the JSON name of the top-level request
// field the path binds; Body is "*", "", or a JSON field name. Unserved lists
// the resource patterns of the method's other bindings, which no route serves.
type Transcoding struct { RPC, REST, Verb, Path, Field, Body string; Unserved []string }
`)
}

// storageRoutes generates the Storage REST route table from the pinned
// discovery document, checksum-verified against the manifest.
func storageRoutes() []byte {
	raw := readDiscovery("api/discovery/storage-v1.json", "api/discovery/manifest.json", "Storage")
	var discovery resource
	must(json.Unmarshal(raw, &discovery))
	routes := storageResourceRoutes(nil, discovery)
	sort.Slice(routes, func(i, j int) bool { a, b := routes[i], routes[j]; return a.Path+a.Verb < b.Path+b.Verb })
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/genapi; DO NOT EDIT.\npackage generated\n\nimport \"github.com/evanmarshall/gcp-local/api/generated/contract\"\n\nvar StorageRoutes = []contract.Route{\n")
	for _, r := range routes {
		fmt.Fprintf(&out, "{Method: %q, Verb: %q, Path: %q, JSONBody: %v, Media: %v},\n", r.ID, r.Verb, r.Path, r.JSON, r.Media)
	}
	out.WriteString("}\n")
	return out.Bytes()
}

// storageParameters generates the query parameter names the pinned Storage
// discovery document defines for each method and for every method. GCP
// ignores a query parameter its API does not define, so the provider uses
// these lists to tell an ignored parameter from a defined one it refuses.
func storageParameters() []byte {
	raw := readDiscovery("api/discovery/storage-v1.json", "api/discovery/manifest.json", "Storage")
	var discovery struct {
		resource
		Parameters map[string]any `json:"parameters"`
	}
	must(json.Unmarshal(raw, &discovery))
	methods := map[string][]string{}
	storageMethodParameters(methods, discovery.resource)
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/genapi; DO NOT EDIT.\npackage generated\n\n")
	out.WriteString("// StorageGlobalParameters are the query parameters discovery defines for every Storage method.\n")
	fmt.Fprintf(&out, "var StorageGlobalParameters = %#v\n\n", slices.Sorted(maps.Keys(discovery.Parameters)))
	out.WriteString("// StorageQueryParameters are the query parameters discovery defines for each Storage method.\nvar StorageQueryParameters = map[string][]string{\n")
	for _, id := range slices.Sorted(maps.Keys(methods)) {
		fmt.Fprintf(&out, "%q: %s,\n", id, strings.TrimPrefix(fmt.Sprintf("%#v", methods[id]), "[]string"))
	}
	out.WriteString("}\n")
	return out.Bytes()
}

// storageMethodParameters records the sorted query parameters of every
// method of r and its child resources.
func storageMethodParameters(methods map[string][]string, r resource) {
	for _, m := range r.Methods {
		names := []string{}
		for name, parameter := range m.Parameters {
			if parameter.Location == "query" {
				names = append(names, name)
			}
		}
		sort.Strings(names)
		methods[m.ID] = names
	}
	for _, child := range r.Resources {
		storageMethodParameters(methods, child)
	}
}

// storageResourceRoutes appends the rows for every method of r and its
// child resources.
func storageResourceRoutes(routes []route, r resource) []route {
	for _, m := range r.Methods {
		routes = append(routes, storageMethodRoutes(m)...)
	}
	for _, child := range r.Resources {
		routes = storageResourceRoutes(routes, child)
	}
	return routes
}

// storageMethodRoutes lists one method's plain, download, and upload rows.
func storageMethodRoutes(m method) []route {
	// A method with media upload protocols serves every body shape on its
	// plain path too (uploadType=media posts raw bytes), so the plain row
	// passes the body through for the provider to parse.
	jsonBody := len(m.Request) > 0 && m.Media == nil
	routes := []route{{m.ID, m.Verb, "/storage/v1/" + m.Path, jsonBody, m.Media != nil}}
	if m.Download {
		routes = append(routes, route{m.ID, m.Verb, "/download/storage/v1/" + m.Path, false, false})
	}
	if m.Media != nil {
		for _, p := range m.Media.Protocols {
			routes = append(routes, route{m.ID, m.Verb, p.Path, false, true})
		}
		// The resumable protocol continues a session with PUT (chunks and
		// status queries) and cancels it with DELETE on the session URI,
		// which is the simple upload path plus upload_id. Discovery
		// describes the protocol but lists no method for these verbs.
		if _, resumable := m.Media.Protocols["resumable"]; resumable {
			for _, verb := range []string{http.MethodPut, http.MethodDelete} {
				routes = append(routes, route{m.ID, verb, "/upload/storage/v1/" + m.Path, false, true})
			}
		}
	}
	return routes
}

// storageXMLRoutes generates the XML API object slice that V4 signed URLs and
// the Go client's reads address. The path is a catch-all, so the gateway
// matches it after every other route. The object is the rest of the path,
// unescaped whole ({object=***}): the Go client escapes "/" in object names.
func storageXMLRoutes() []byte {
	rows := []route{
		{"storage.xml.objects.get", http.MethodGet, "/{bucket}/{object=***}", false, false},
		{"storage.xml.objects.put", http.MethodPut, "/{bucket}/{object=***}", false, true},
	}
	return routeTable("StorageXMLRoutes", "is the Cloud Storage XML API object route table slice.", rows)
}

// pubsubDispatch generates the Pub/Sub forwarding stubs and resource selectors
// from the pinned module's protoc descriptors.
func pubsubDispatch() []byte {
	out := header(`// Code generated by tools/genapi; DO NOT EDIT.
package generated
import (
 "context"
 "github.com/evanmarshall/gcp-local/api/generated/contract"
 pb "cloud.google.com/go/pubsub/v2/apiv1/pubsubpb"
 "google.golang.org/grpc/codes"
 "google.golang.org/grpc/status"
 "google.golang.org/protobuf/proto"
 "google.golang.org/protobuf/types/known/emptypb"
)
`)
	var descriptors bytes.Buffer
	descriptors.WriteString("var PubSubMethods = []contract.RPC{\n")
	// SchemaService lives in schema.proto beside the Publisher and Subscriber.
	var services []protoreflect.ServiceDescriptor
	for _, file := range []protoreflect.FileDescriptor{pb.File_google_pubsub_v1_pubsub_proto, pb.File_google_pubsub_v1_schema_proto} {
		for i := range file.Services().Len() {
			services = append(services, file.Services().Get(i))
		}
	}
	for _, service := range services {
		name := string(service.Name())
		fmt.Fprintf(&out, "type %sServer struct { pb.Unimplemented%sServer; Dispatch contract.PubSubDispatch }\n", name, name)
		for j := range service.Methods().Len() {
			m := service.Methods().Get(j)
			methodName := string(m.Name())
			id := "/" + string(service.FullName()) + "/" + methodName
			input, output := goType(m.Input()), goType(m.Output())
			field, pattern, streaming := methodSelector(m, id)
			if streaming {
				fmt.Fprintf(&out, "func(s *%sServer) %s(stream pb.%s_%sServer) error { return s.Dispatch.Stream(%q,stream) }\n", name, methodName, name, methodName, id)
			} else {
				unaryStub(&out, name, methodName, input, output, id)
			}
			if field == "" {
				panic("Missing resource selector for " + id)
			}
			rpcDescriptor(&descriptors, id, field, pattern, streaming, input, output)
		}
	}
	descriptors.WriteString("}\n")
	out.Write(descriptors.Bytes())
	return out.Bytes()
}

// methodSelector resolves the wire resource field and pattern for one method.
func methodSelector(m protoreflect.MethodDescriptor, id string) (string, string, bool) {
	methodName := string(m.Name())
	streaming := m.IsStreamingClient() || m.IsStreamingServer()
	if streaming {
		if methodName != "StreamingPull" || !m.IsStreamingClient() || !m.IsStreamingServer() {
			panic("Unsupported new streaming shape; update generator")
		}
		return "subscription", "projects/*/subscriptions/*", true
	}
	if proto.HasExtension(m.Options(), annotations.E_Http) {
		rule, ok := proto.GetExtension(m.Options(), annotations.E_Http).(*annotations.HttpRule)
		if !ok {
			panic("method " + methodName + " has a non-HTTP annotation")
		}
		path := rulePath(rule)
		if match := resourceVariable.FindStringSubmatch(path); match != nil {
			return match[1], match[2], false
		}
	}
	panic("Missing resource selector for " + id)
}

