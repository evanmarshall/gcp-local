#!/usr/bin/env python3
"""Reproduce the small pinned acceptance slice and its explicit local adaptations."""

import hashlib
import json
import subprocess
import sys
from pathlib import Path


def main() -> int:
    """Reproduce the pinned acceptance slice and its local adaptations."""
    root = Path(__file__).resolve().parents[1]
    source = root / "third_party/terraform-provider-google"
    manifest = json.loads((source / "manifest.json").read_text())
    raw = (source / "functions.json").read_bytes()
    if hashlib.sha256(raw).hexdigest() != manifest["functions_sha256"]:
        raise RuntimeError("functions.json does not match the packaged manifest digest")
    functions = json.loads(raw)
    header = """// Copyright IBM Corp. 2014, 2026
// SPDX-License-Identifier: MPL-2.0
// Code generated by scripts/generate_terraform_tests.py; DO NOT EDIT.
// Upstream assertions retained; local fixture/factory adaptations documented in audit.md.
package terraform_test
import (
 "encoding/base64"
 "encoding/binary"
 "fmt"
 "hash/crc32"
 "io/ioutil"
 "os"
 "testing"
 "github.com/hashicorp/terraform-plugin-testing/helper/resource"
)
const objectName = "tf-gce-test"
"""
    proto_factories = "ProtoV5ProviderFactories: acctest.ProtoV5ProviderFactories(t)"
    replacements = {
        "\tt.Parallel()\n": "",
        "acctest.TestBucketName(t)": "ownedBucket(t)",
        'fmt.Sprintf("tf-test-acl-bucket-%d", acctest.RandInt(t))': "ownedBucket(t)",
        "acctest.VcrTest": "localCase",
        "acctest.AccTestPreCheck": "preCheck",
        proto_factories: "ExternalProviders: pinnedProvider()",
        "envvar.GetTestProjectFromEnv()": "projectID",
    }
    for name in sorted(functions):
        value = functions[name]
        for before, after in replacements.items():
            value = value.replace(before, after)
        # The approved fixture is single-region: GCP omits RPO there.
        if name == "TestAccStorageBucket_basic":
            value = value.replace(
                "resource.TestCheckResourceAttr(\n\t\t\t\t\t\t"
                '"google_storage_bucket.bucket", "rpo", "DEFAULT")',
                "resource.TestCheckNoResourceAttr(\n\t\t\t\t\t\t"
                '"google_storage_bucket.bucket", "rpo")',
            )
        header += "\n" + value + "\n"
    formatted = subprocess.check_output([str(root / ".tools/go/bin/gofmt")], input=header.encode())
    output = root / "tests/terraform/runner/upstream_test.go"
    if "--check" in sys.argv:
        if output.read_bytes() != formatted:
            raise SystemExit("Terraform acceptance slice is stale")
    else:
        output.write_bytes(formatted)


if __name__ == "__main__":
    main()
